@pytest.mark.parametrize(
    ("fault_type", "validator"),
    [
        (FaultType.VOLTAGE_SAG, lambda r: r["voltage_l1"] < 207.0),
        (FaultType.VOLTAGE_SWELL, lambda r: r["voltage_l1"] > 253.0),
        (FaultType.DEMAND_SPIKE, lambda r: r["active_power_kw"] >= 30.0),
        (FaultType.PHASE_IMBALANCE, lambda r: abs(r["voltage_l1"] - r["voltage_l2"]) > 15.0),
        (FaultType.LOW_POWER_FACTOR, lambda r: r["power_factor"] < 0.8),
        (FaultType.FREQUENCY_EXCURSION, lambda r: r["frequency_hz"] < 49.5 or r["frequency_hz"] > 50.5),
    ],
)
def test_fault_injection_ranges_and_schema(
    telemetry_schema: dict,
    fault_type: FaultType,
    validator: Any,
) -> None:
    """Test that all fault types trigger expected ranges and still conform to schema."""
    meter = SmartMeter(meter_id=7)
    base_reading = meter.generate_reading()

    faulty = apply_fault(base_reading, fault_type)

    assert validator(faulty), f"Fault {fault_type} did not satisfy range validation"
    assert faulty["status"] == "WARNING"

    # Must remain schema-valid even under anomalous conditions
    jsonschema.validate(instance=faulty, schema=telemetry_schema)


def test_fault_injector_stochastic() -> None:
    """Test FaultInjector stochastic triggering."""
    injector = FaultInjector(fault_probability=1.0)  # Always inject
    meter = SmartMeter(meter_id=99)
    reading = meter.generate_reading()

    faulty, fault_type = injector.maybe_inject(reading)
    assert fault_type is not None
    assert faulty["status"] == "WARNING"

    # Zero probability
    injector_zero = FaultInjector(fault_probability=0.0)
    normal, fault_none = injector_zero.maybe_inject(reading)
    assert fault_none is None
    assert normal["status"] == "OK"


def test_individual_fault_functions() -> None:
    """Directly test individual fault injection functions."""
    meter = SmartMeter(meter_id=1)
    base = meter.generate_reading()

    # 1. Voltage sag
    sag = inject_voltage_sag(base, voltage_v=192.5)
    assert sag["voltage_l1"] == 192.5
    assert sag["status"] == "WARNING"

    # 2. Voltage swell
    swell = inject_voltage_swell(base, voltage_v=268.0)
    assert swell["voltage_l1"] == 268.0
    assert swell["status"] == "WARNING"

    # 3. Demand spike
    spike = inject_demand_spike(base, spike_kw=38.5)
    assert spike["active_power_kw"] == 38.5
    assert spike["current_l1"] > 40.0  # Proportionally scaled

    # 4. Phase imbalance
    imb = inject_phase_imbalance(base, v_l1=238.0, v_l2=212.0, v_l3=230.0)
    assert imb["voltage_l1"] == 238.0
    assert imb["voltage_l2"] == 212.0

    # 5. Low power factor
    lpf = inject_low_power_factor(base, pf=0.62)
    assert lpf["power_factor"] == 0.62

    # 6. Frequency excursion
    fe_low = inject_frequency_excursion(base, freq_hz=49.1)
    assert fe_low["frequency_hz"] == 49.1
    fe_high = inject_frequency_excursion(base, freq_hz=50.9)
    assert fe_high["frequency_hz"] == 50.9


def test_replay_buffer_offline_burst_and_duplicates(telemetry_schema: dict) -> None:
    """Test offline gateway buffering, out-of-order burst, and duplicate packet injection."""
    replay = ReplayBuffer(buffer_duration_seconds=30.0, duplicate_ratio=0.25)
    meter = SmartMeter(meter_id=12)

    t_start = 1000.0
    num_packets = 20

    # Simulate accumulating 20 packets over 30s
    for i in range(num_packets):
        ts = datetime(2026, 11, 12, 10, 0, i, tzinfo=UTC)
        reading = meter.generate_reading(timestamp=ts)
        replay.add(reading, current_time=t_start + (i * 1.5))

    assert len(replay) == num_packets
    # At t = 1010s, should not flush (only 10s elapsed)
    assert not replay.should_flush(current_time=t_start + 10.0)
    # At t = 1030.1s, should flush (>= 30s)
    assert replay.should_flush(current_time=t_start + 30.1)

    # Flush burst
    burst = replay.flush_burst()

    # Buffer must be cleared
    assert len(replay) == 0

    # Burst must contain original packets + intentional duplicates
    # With duplicate_ratio=0.25 on 20 packets: 5 duplicates expected => total 25 packets
    assert len(burst) >= num_packets
    expected_duplicates = max(1, int(num_packets * 0.25))
    assert len(burst) == num_packets + expected_duplicates

    # Detect duplicate (meter_id, timestamp) pairs
    seen = set()
    duplicates_found = 0
    for pkt in burst:
        jsonschema.validate(instance=pkt, schema=telemetry_schema)
        pair = (pkt["meter_id"], pkt["timestamp"])
        if pair in seen:
            duplicates_found += 1
        else:
            seen.add(pair)

    assert duplicates_found == expected_duplicates, f"Expected {expected_duplicates} duplicates, got {duplicates_found}"

    # Verify that burst is not in strict monotonic chronological order (shuffled)
    timestamps = [p["timestamp"] for p in burst]
    is_sorted = timestamps == sorted(timestamps)
    assert not is_sorted, "Burst packets should be scrambled out-of-order"


