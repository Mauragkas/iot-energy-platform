# Locate JSON schema
SCHEMA_PATH = Path(__file__).resolve().parent.parent.parent / "docs" / "schemas" / "telemetry.json"


@pytest.fixture(scope="session")
def telemetry_schema() -> dict:
    """Load JSON Schema definition for telemetry metrics."""
    assert SCHEMA_PATH.exists(), f"Schema file not found at {SCHEMA_PATH}"
    with open(SCHEMA_PATH) as f:
        return json.load(f)


def test_schema_file_valid(telemetry_schema: dict) -> None:
    """Ensure the schema itself is a valid JSON schema."""
    assert telemetry_schema["title"] == "SmartMeterTelemetry"
    assert "meter_id" in telemetry_schema["required"]
    assert "timestamp" in telemetry_schema["required"]


def test_meter_reading_conforms_to_schema(telemetry_schema: dict) -> None:
    """Verify that readings generated by SmartMeter pass strict JSON schema validation."""
    meter = SmartMeter(meter_id=42, zone="north")
    now = datetime.now(UTC)

    # Test readings at different times of day to exercise diurnal curves
    for hour_offset in [0, 4, 8, 12, 19, 23]:
        ts = now.replace(hour=hour_offset, minute=15, second=30)
        reading = meter.generate_reading(timestamp=ts)

        # Validate against strict schema (will raise jsonschema.ValidationError on failure)
        jsonschema.validate(instance=reading, schema=telemetry_schema)

        assert reading["meter_id"] == "MZ-3P-0042"
        assert reading["status"] == "OK"
        assert 220.0 <= reading["voltage_l1"] <= 245.0
        assert 220.0 <= reading["voltage_l2"] <= 245.0
        assert 220.0 <= reading["voltage_l3"] <= 245.0
        assert reading["current_l1"] > 0
        assert reading["current_l2"] > 0
        assert reading["current_l3"] > 0
        assert reading["active_power_kw"] > 0
        assert reading["total_energy_kwh"] > 0
        assert 0.90 <= reading["power_factor"] <= 1.0
        assert 49.8 <= reading["frequency_hz"] <= 50.2
        assert 180 <= reading["zigbee_lqi"] <= 250


def test_continuous_energy_accumulation() -> None:
    """Test that cumulative total_energy_kwh continuously and monotonically accumulates."""
    meter = SmartMeter(meter_id="MZ-3P-0100", initial_energy_kwh=100.0)
    t0 = datetime(2026, 11, 12, 12, 0, 0, tzinfo=UTC)

    reading_0 = meter.generate_reading(timestamp=t0, override_delta_seconds=2.0)
    e0 = reading_0["total_energy_kwh"]

    # Advance time by 3600 seconds (1 hour)
    t1 = t0 + timedelta(seconds=3600)
    reading_1 = meter.generate_reading(timestamp=t1)
    e1 = reading_1["total_energy_kwh"]

    assert e1 > e0
    # Expected delta ~ active_power_kw * 1 hour
    delta_energy = e1 - e0
    assert pytest.approx(delta_energy, rel=0.05) == reading_1["active_power_kw"]


def test_diurnal_curve_profile() -> None:
    """Test diurnal curve characteristics (night baseline, morning peak, evening peak)."""
    night_factor = calculate_diurnal_factor(3.0)  # 03:00 AM
    morning_factor = calculate_diurnal_factor(8.0)  # 08:00 AM
    midday_factor = calculate_diurnal_factor(13.0)  # 01:00 PM
    evening_factor = calculate_diurnal_factor(19.5)  # 07:30 PM

    assert night_factor < morning_factor
    assert morning_factor < evening_factor
    assert night_factor < midday_factor
    # Evening peak is the highest load period
    assert evening_factor > midday_factor
    assert 0.2 < night_factor < 0.6
    assert 0.9 < evening_factor < 1.4


